export const cabinetMessages: Record<CabinetLang, typeof ru> = { ru, en }

export function parseCabinetLang(raw: unknown): CabinetLang {
  const v = String(raw ?? '').replace(/^"+|"+$/g, '').toLowerCase()
  return v.startsWith('en') ? 'en' : 'ru'
}

export function cabinetLookup(lang: CabinetLang, key: string, vars?: Record<string, string | number>) {
  const parts = key.split('.')
  let cur: unknown = cabinetMessages[lang]
  for (const p of parts) {
    if (cur && typeof cur === 'object' && p in (cur as object)) {
      cur = (cur as Record<string, unknown>)[p]
    }
    else {
      cur = undefined
      break
    }
  }
  let s = typeof cur === 'string' ? cur : key
  if (vars) {
    s = s.replace(/\{(\w+)\}/g, (_, k: string) => (vars[k] == null ? '' : String(vars[k])))
  }
  return s
}
